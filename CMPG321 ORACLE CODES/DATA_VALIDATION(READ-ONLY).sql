SELECT RIDE_CATEGORY, COUNT(*) AS TOTAL_TRIPS
FROM TRIP_HEADERS
GROUP BY RIDE_CATEGORY
ORDER BY TOTAL_TRIPS DESC;


-- R6. Check Allowed Values
SELECT CHECK_NAME, INVALID_ROWS,
       CASE WHEN INVALID_ROWS = 0 THEN 'PASS' ELSE 'FAIL' END AS RESULT
FROM (
    SELECT 'TRIP_STATUS' AS CHECK_NAME, COUNT(*) AS INVALID_ROWS
    FROM TRIP_HEADERS
    WHERE TRIP_STATUS NOT IN ('COMPLETED','CANCELLED_BY_RIDER','CANCELLED_BY_DRIVER')
    UNION ALL
    SELECT 'PAYMENT_METHOD', COUNT(*)
    FROM TRIP_FARE_BREAKDOWN
    WHERE PAYMENT_METHOD NOT IN ('CASH','CREDIT_CARD','DEBIT_CARD','EFT_OZOW','IN_APP_WALLET')
    UNION ALL
    SELECT 'PREFERRED_PAYMENT', COUNT(*)
    FROM SA_RIDERS
    WHERE PREFERRED_PAYMENT NOT IN ('CASH','CREDIT_CARD','DEBIT_CARD','EFT_OZOW','IN_APP_WALLET')
    UNION ALL
    SELECT 'CANCELLATION_REASON', COUNT(*)
    FROM TRIP_HEADERS
    WHERE CANCELLATION_REASON IS NOT NULL
      AND CANCELLATION_REASON <> 'N/A'
      AND CANCELLATION_REASON NOT IN ('CHANGED_MIND','DRIVER_TOO_FAR','SAFETY_CONCERN',
                                      'RIDER_NO_SHOW','PRICING_SURGE','TRAFFIC_DELAY')
);


-- E. CANCELLATION REASON LOGIC

-- R7. Check Cancellation Reasons by Trip Status
SELECT TRIP_STATUS,
       COUNT(*) AS TRIPS,
       SUM(CASE WHEN CANCELLATION_REASON IS NULL THEN 1 ELSE 0 END) AS NULL_REASONS,
       SUM(CASE WHEN CANCELLATION_REASON = 'N/A' THEN 1 ELSE 0 END) AS NA_REASONS,
       SUM(CASE WHEN CANCELLATION_REASON IS NOT NULL
                 AND CANCELLATION_REASON <> 'N/A' THEN 1 ELSE 0 END) AS ACTUAL_REASONS
FROM TRIP_HEADERS
GROUP BY TRIP_STATUS
ORDER BY TRIP_STATUS;



-- F. ZERO-VALUE FARES 


-- R8. Check Zero Fares, Distances and Durations.
SELECT t.TRIP_STATUS,
       COUNT(*) AS TOTAL_TRIPS,
       SUM(CASE WHEN f.TOTAL_FARE_ZAR = 0 THEN 1 ELSE 0 END) AS ZERO_FARE_TRIPS,
       SUM(CASE WHEN f.TOTAL_FARE_ZAR > 0 THEN 1 ELSE 0 END) AS POSITIVE_FARE_TRIPS,
       SUM(CASE WHEN f.DISTANCE_KM = 0 AND f.DURATION_MINUTES = 0
                THEN 1 ELSE 0 END) AS ZERO_DISTANCE_AND_DURATION
FROM TRIP_HEADERS t
JOIN TRIP_FARE_BREAKDOWN f ON t.TRIP_ID = f.TRIP_ID
GROUP BY t.TRIP_STATUS
ORDER BY t.TRIP_STATUS;



-- G. NUMERIC RANGES


-- R9. Check Numerical Values
SELECT CHECK_NAME, INVALID_ROWS,
       CASE WHEN INVALID_ROWS = 0 THEN 'PASS' ELSE 'FAIL' END AS RESULT
FROM (
    SELECT 'Negative distance' AS CHECK_NAME, COUNT(*) AS INVALID_ROWS FROM TRIP_FARE_BREAKDOWN WHERE DISTANCE_KM < 0
    UNION ALL SELECT 'Negative duration', COUNT(*) FROM TRIP_FARE_BREAKDOWN WHERE DURATION_MINUTES < 0
    UNION ALL SELECT 'Surge multiplier below 1.0', COUNT(*) FROM TRIP_FARE_BREAKDOWN WHERE SURGE_MULTIPLIER < 1
    UNION ALL SELECT 'Negative base fare', COUNT(*) FROM TRIP_FARE_BREAKDOWN WHERE BASE_FARE_ZAR < 0
    UNION ALL SELECT 'Negative tolls', COUNT(*) FROM TRIP_FARE_BREAKDOWN WHERE TOLLS_ZAR < 0
    UNION ALL SELECT 'Negative tip', COUNT(*) FROM TRIP_FARE_BREAKDOWN WHERE TIP_ZAR < 0
    UNION ALL SELECT 'Negative total fare', COUNT(*) FROM TRIP_FARE_BREAKDOWN WHERE TOTAL_FARE_ZAR < 0
    UNION ALL SELECT 'Negative platform commission', COUNT(*) FROM TRIP_FARE_BREAKDOWN WHERE PLATFORM_COMMISSION_ZAR < 0
    UNION ALL SELECT 'Negative driver payout', COUNT(*) FROM TRIP_FARE_BREAKDOWN WHERE DRIVER_PAYOUT_ZAR < 0
    UNION ALL SELECT 'Review rating (rider of driver) outside 0-5', COUNT(*) FROM TRIP_REVIEWS WHERE RIDER_RATING_OF_DRIVER NOT BETWEEN 0 AND 5
    UNION ALL SELECT 'Review rating (driver of rider) outside 0-5', COUNT(*) FROM TRIP_REVIEWS WHERE DRIVER_RATING_OF_RIDER NOT BETWEEN 0 AND 5
    UNION ALL SELECT 'Driver rating outside 0-5', COUNT(*) FROM SA_DRIVERS WHERE DRIVER_RATING NOT BETWEEN 0 AND 5
    UNION ALL SELECT 'Commission outside 0-1 (stored as a fraction)', COUNT(*) FROM SA_DRIVERS WHERE PLATFORM_COMMISSION_PCT NOT BETWEEN 0 AND 1
    UNION ALL SELECT 'Vehicle year outside 1990-2030', COUNT(*) FROM VEHICLES WHERE YEAR NOT BETWEEN 1990 AND 2030
);

-- R10. Summarise Numerical Values
SELECT MIN(DISTANCE_KM) AS MIN_KM, MAX(DISTANCE_KM) AS MAX_KM,
       MIN(DURATION_MINUTES) AS MIN_MINUTES, MAX(DURATION_MINUTES) AS MAX_MINUTES,
       MIN(SURGE_MULTIPLIER) AS MIN_SURGE, MAX(SURGE_MULTIPLIER) AS MAX_SURGE,
       MIN(TOTAL_FARE_ZAR) AS MIN_FARE_ZAR, MAX(TOTAL_FARE_ZAR) AS MAX_FARE_ZAR,
       ROUND(AVG(TOTAL_FARE_ZAR), 2) AS AVG_FARE_ZAR
FROM TRIP_FARE_BREAKDOWN;

-- R10b. How often each tip amount occurs

SELECT TIP_ZAR, COUNT(*) AS NUMBER_OF_TRIPS
FROM TRIP_FARE_BREAKDOWN
GROUP BY TIP_ZAR
ORDER BY TIP_ZAR;



-- H. FARE RECONCILIATION

--R11. Check Fare Components for Completed Trips

SELECT COUNT(*) AS COMPLETED_FARE_MISMATCHES
FROM TRIP_HEADERS t
JOIN TRIP_FARE_BREAKDOWN f ON t.TRIP_ID = f.TRIP_ID
WHERE t.TRIP_STATUS = 'COMPLETED'
  AND f.TOTAL_FARE_ZAR < (f.BASE_FARE_ZAR + f.TOLLS_ZAR + f.TIP_ZAR);

-- R12. Check Fare, Commission and Driver Payout
SELECT COUNT(*) AS POSITIVE_FARE_RECORDS,
       SUM(CASE WHEN ABS(TOTAL_FARE_ZAR - (PLATFORM_COMMISSION_ZAR + DRIVER_PAYOUT_ZAR)) <= 0.05
                THEN 1 ELSE 0 END) AS MATCH_COUNT,
       SUM(CASE WHEN ABS(TOTAL_FARE_ZAR - (PLATFORM_COMMISSION_ZAR + DRIVER_PAYOUT_ZAR)) > 0.05
                THEN 1 ELSE 0 END) AS DIFFERENCE_COUNT
FROM TRIP_FARE_BREAKDOWN
WHERE TOTAL_FARE_ZAR > 0;


-- I. DUPLICATES

-- R13. Check Duplicate IDs, Number Plates and Mobile Numbers
SELECT CHECK_NAME, DUPLICATES,
       CASE WHEN DUPLICATES = 0 THEN 'PASS' ELSE 'FAIL' END AS RESULT
FROM (
    SELECT 'Duplicate trip IDs' AS CHECK_NAME,
           COUNT(*) - COUNT(DISTINCT TRIP_ID) AS DUPLICATES
    FROM TRIP_HEADERS
    UNION ALL
    SELECT 'Duplicate licence plates', COUNT(*) - COUNT(DISTINCT LICENSE_PLATE) FROM VEHICLES
    UNION ALL
    SELECT 'Duplicate rider mobile numbers', COUNT(*) - COUNT(DISTINCT MOBILE_NUMBER) FROM SA_RIDERS
);



-- J. DATES VLAIDATIONS


-- R14. Check Date Ranges and Future Dates

SELECT 'TRIP_HEADERS.REQUEST_TIMESTAMP' AS COLUMN_CHECKED,
       TO_CHAR(MIN(REQUEST_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS') AS EARLIEST,
       TO_CHAR(MAX(REQUEST_TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS') AS LATEST,
       SUM(CASE WHEN REQUEST_TIMESTAMP > SYSDATE THEN 1 ELSE 0 END) AS FUTURE_DATES
FROM TRIP_HEADERS
UNION ALL
SELECT 'SA_RIDERS.ACCOUNT_CREATED_DATE',
       TO_CHAR(MIN(ACCOUNT_CREATED_DATE), 'YYYY-MM-DD'),
       TO_CHAR(MAX(ACCOUNT_CREATED_DATE), 'YYYY-MM-DD'),
       SUM(CASE WHEN ACCOUNT_CREATED_DATE > SYSDATE THEN 1 ELSE 0 END)
FROM SA_RIDERS;

-- R15. Check Trips Requested Before Rider Registration
SELECT COUNT(*) AS TRIPS_BEFORE_ACCOUNT_CREATED,
       COUNT(DISTINCT t.RIDER_ID) AS RIDERS_AFFECTED
FROM TRIP_HEADERS t
JOIN SA_RIDERS r ON t.RIDER_ID = r.RIDER_ID
WHERE t.REQUEST_TIMESTAMP < r.ACCOUNT_CREATED_DATE;


-- K. QUICK EVIDENCE CHECKS 
-- R16. Check South African Mobile Number Formats.
SELECT CHECK_NAME,
       INVALID_ROWS,
       CASE
           WHEN INVALID_ROWS = 0 THEN 'PASS'
           ELSE 'FAIL'
       END AS RESULT
FROM (
    SELECT 'Mobile numbers missing' AS CHECK_NAME,
           COUNT(*) AS INVALID_ROWS
    FROM SA_RIDERS
    WHERE MOBILE_NUMBER IS NULL

    UNION ALL

    SELECT 'Mobile numbers not 11 digits',
           COUNT(*)
    FROM SA_RIDERS
    WHERE MOBILE_NUMBER IS NOT NULL
      AND LENGTH(TO_CHAR(MOBILE_NUMBER)) <> 11

    UNION ALL

    SELECT 'Mobile numbers not starting with 27',
           COUNT(*)
    FROM SA_RIDERS
    WHERE MOBILE_NUMBER IS NOT NULL
      AND SUBSTR(TO_CHAR(MOBILE_NUMBER), 1, 2) <> '27'
);

-- R17. Check Leading and Trailing Spaces
SELECT CHECK_NAME, INVALID_ROWS,
       CASE WHEN INVALID_ROWS = 0 THEN 'PASS' ELSE 'FAIL' END AS RESULT
FROM (
    SELECT 'TRIP_STATUS' AS CHECK_NAME, COUNT(*) AS INVALID_ROWS
    FROM TRIP_HEADERS WHERE TRIP_STATUS <> TRIM(TRIP_STATUS)
    UNION ALL
    SELECT 'RIDE_CATEGORY', COUNT(*) FROM TRIP_HEADERS WHERE RIDE_CATEGORY <> TRIM(RIDE_CATEGORY)
    UNION ALL
    SELECT 'CANCELLATION_REASON', COUNT(*) FROM TRIP_HEADERS
    WHERE CANCELLATION_REASON IS NOT NULL AND CANCELLATION_REASON <> TRIM(CANCELLATION_REASON)
    UNION ALL
    SELECT 'RIDER_ID', COUNT(*) FROM SA_RIDERS WHERE RIDER_ID <> TRIM(RIDER_ID)
    UNION ALL
    SELECT 'DRIVER_ID', COUNT(*) FROM SA_DRIVERS WHERE DRIVER_ID <> TRIM(DRIVER_ID)
);

-- R18. Check Reviews Against Trip Status
SELECT t.TRIP_STATUS, COUNT(*) AS NUMBER_OF_REVIEWS
FROM TRIP_REVIEWS rv
JOIN TRIP_HEADERS t ON rv.TRIP_ID = t.TRIP_ID
GROUP BY t.TRIP_STATUS
ORDER BY t.TRIP_STATUS;

