-- 04b: DATA VALIDATION 

-- R1. Check Table Record Counts
SELECT TABLE_NAME, EXPECTED_ROWS, ACTUAL_ROWS,
       CASE WHEN EXPECTED_ROWS = ACTUAL_ROWS
            THEN 'PASS' ELSE 'FAIL' END AS RESULT
FROM (
    SELECT 'PRICING_SURGE_ZONES' AS TABLE_NAME, 9 AS EXPECTED_ROWS, COUNT(*) AS ACTUAL_ROWS FROM PRICING_SURGE_ZONES
    UNION ALL SELECT 'SA_DRIVERS', 800, COUNT(*) FROM SA_DRIVERS
    UNION ALL SELECT 'SA_RIDERS', 1200, COUNT(*) FROM SA_RIDERS
    UNION ALL SELECT 'VEHICLES', 800, COUNT(*) FROM VEHICLES
    UNION ALL SELECT 'TRIP_HEADERS', 50000, COUNT(*) FROM TRIP_HEADERS
    UNION ALL SELECT 'TRIP_FARE_BREAKDOWN', 50000, COUNT(*) FROM TRIP_FARE_BREAKDOWN
    UNION ALL SELECT 'TRIP_REVIEWS', 25055, COUNT(*) FROM TRIP_REVIEWS
)
ORDER BY TABLE_NAME;


-- B. KEYS AND RELATIONSHIPS
-- R2. Check Primary Key Uniqueness
SELECT TABLE_NAME, TOTAL_ROWS, NON_NULL_KEYS, UNIQUE_KEYS,
       CASE WHEN TOTAL_ROWS = NON_NULL_KEYS AND TOTAL_ROWS = UNIQUE_KEYS
            THEN 'PASS' ELSE 'FAIL' END AS RESULT
FROM (
    SELECT 'SA_DRIVERS' AS TABLE_NAME, COUNT(*) AS TOTAL_ROWS,
           COUNT(DRIVER_ID) AS NON_NULL_KEYS, COUNT(DISTINCT DRIVER_ID) AS UNIQUE_KEYS
    FROM SA_DRIVERS
    UNION ALL SELECT 'SA_RIDERS', COUNT(*), COUNT(RIDER_ID), COUNT(DISTINCT RIDER_ID) FROM SA_RIDERS
    UNION ALL SELECT 'VEHICLES', COUNT(*), COUNT(VEHICLE_ID), COUNT(DISTINCT VEHICLE_ID) FROM VEHICLES
    UNION ALL SELECT 'PRICING_SURGE_ZONES', COUNT(*), COUNT(ZONE_ID), COUNT(DISTINCT ZONE_ID) FROM PRICING_SURGE_ZONES
    UNION ALL SELECT 'TRIP_HEADERS', COUNT(*), COUNT(TRIP_ID), COUNT(DISTINCT TRIP_ID) FROM TRIP_HEADERS
    UNION ALL SELECT 'TRIP_FARE_BREAKDOWN', COUNT(*), COUNT(TRIP_ID), COUNT(DISTINCT TRIP_ID) FROM TRIP_FARE_BREAKDOWN
    UNION ALL SELECT 'TRIP_REVIEWS', COUNT(*), COUNT(REVIEW_ID), COUNT(DISTINCT REVIEW_ID) FROM TRIP_REVIEWS
)
ORDER BY TABLE_NAME;


-- R3. Check Foreign Key Relationships
SELECT RELATIONSHIP, UNMATCHED_RECORDS,
       CASE WHEN UNMATCHED_RECORDS = 0 THEN 'PASS' ELSE 'FAIL' END AS RESULT
FROM (
    SELECT 'TRIP_HEADERS -> SA_RIDERS' AS RELATIONSHIP, COUNT(*) AS UNMATCHED_RECORDS
    FROM TRIP_HEADERS t
    WHERE NOT EXISTS (SELECT 1 FROM SA_RIDERS r WHERE r.RIDER_ID = t.RIDER_ID)
    UNION ALL
    SELECT 'TRIP_HEADERS -> SA_DRIVERS', COUNT(*)
    FROM TRIP_HEADERS t
    WHERE NOT EXISTS (SELECT 1 FROM SA_DRIVERS d WHERE d.DRIVER_ID = t.DRIVER_ID)
    UNION ALL
    SELECT 'TRIP_HEADERS -> PRICING_SURGE_ZONES', COUNT(*)
    FROM TRIP_HEADERS t
    WHERE NOT EXISTS (SELECT 1 FROM PRICING_SURGE_ZONES z WHERE z.ZONE_ID = t.ZONE_ID)
    UNION ALL
    SELECT 'TRIP_FARE_BREAKDOWN -> TRIP_HEADERS', COUNT(*)
    FROM TRIP_FARE_BREAKDOWN f
    WHERE NOT EXISTS (SELECT 1 FROM TRIP_HEADERS t WHERE t.TRIP_ID = f.TRIP_ID)
    UNION ALL
    SELECT 'TRIP_REVIEWS -> TRIP_HEADERS', COUNT(*)
    FROM TRIP_REVIEWS rv
    WHERE NOT EXISTS (SELECT 1 FROM TRIP_HEADERS t WHERE t.TRIP_ID = rv.TRIP_ID)
    UNION ALL
    SELECT 'VEHICLES -> SA_DRIVERS', COUNT(*)
    FROM VEHICLES v
    WHERE NOT EXISTS (SELECT 1 FROM SA_DRIVERS d WHERE d.DRIVER_ID = v.DRIVER_ID)
    UNION ALL
    SELECT 'TRIP_HEADERS without a fare record', COUNT(*)
    FROM TRIP_HEADERS t
    WHERE NOT EXISTS (SELECT 1 FROM TRIP_FARE_BREAKDOWN f WHERE f.TRIP_ID = t.TRIP_ID)
);



