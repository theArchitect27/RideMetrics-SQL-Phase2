SELECT (SELECT COUNT(*) FROM VEHICLES) AS TOTAL_VEHICLES,
       (SELECT COUNT(DISTINCT DRIVER_ID) FROM VEHICLES) AS DISTINCT_DRIVERS,
       (SELECT COUNT(*) FROM SA_DRIVERS d
         WHERE NOT EXISTS (SELECT 1 FROM VEHICLES v WHERE v.DRIVER_ID = d.DRIVER_ID))
           AS DRIVERS_WITHOUT_VEHICLES
