-- V24. Validate distance and duration
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    SUM(CASE
        WHEN DISTANCE_KM < 0 THEN 1
        ELSE 0
    END) AS NEGATIVE_DISTANCES,
    SUM(CASE
        WHEN DISTANCE_KM = 0 THEN 1
        ELSE 0
    END) AS ZERO_DISTANCES,
    SUM(CASE
        WHEN DURATION_MINUTES < 0 THEN 1
        ELSE 0
    END) AS NEGATIVE_DURATIONS,
    SUM(CASE
        WHEN DURATION_MINUTES = 0 THEN 1
        ELSE 0
    END) AS ZERO_DURATIONS,
    SUM(CASE
        WHEN DISTANCE_KM IS NULL THEN 1
        ELSE 0
    END) AS MISSING_DISTANCES,
    SUM(CASE
        WHEN DURATION_MINUTES IS NULL THEN 1
        ELSE 0
