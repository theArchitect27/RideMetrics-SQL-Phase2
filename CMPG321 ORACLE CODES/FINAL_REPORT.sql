    SUM(CASE
        WHEN BASE_FARE_ZAR IS NULL THEN 1
        ELSE 0
    END) AS MISSING_BASE_FARES,
    SUM(CASE
        WHEN TOTAL_FARE_ZAR IS NULL THEN 1
        ELSE 0
    END) AS MISSING_TOTAL_FARES,
    SUM(CASE
        WHEN TOLLS_ZAR IS NULL THEN 1
        ELSE 0
    END) AS MISSING_TOLL_AMOUNTS,
    SUM(CASE
        WHEN TIP_ZAR IS NULL THEN 1
        ELSE 0
    END) AS MISSING_TIPS
FROM TRIP_FARE_BREAKDOWN;


-- V20. Check whether total fares are below base fare,
-- tolls and tip combined
SELECT
    COUNT(*) AS FARE_TOTAL_BELOW_COMPONENTS
FROM TRIP_FARE_BREAKDOWN
WHERE TOTAL_FARE_ZAR < (
    BASE_FARE_ZAR + TOLLS_ZAR + TIP_ZAR
);


-- V21. Compare zero and positive fares with trip status
SELECT
    t.TRIP_STATUS,
    COUNT(*) AS TOTAL_TRIPS,
    SUM(CASE
        WHEN f.TOTAL_FARE_ZAR = 0 THEN 1
        ELSE 0
    END) AS ZERO_TOTAL_FARES,
    SUM(CASE
        WHEN f.TOTAL_FARE_ZAR > 0 THEN 1
        ELSE 0
    END) AS POSITIVE_TOTAL_FARES
FROM TRIP_HEADERS t
JOIN TRIP_FARE_BREAKDOWN f
    ON t.TRIP_ID = f.TRIP_ID
GROUP BY t.TRIP_STATUS
ORDER BY t.TRIP_STATUS;


-- V22. Check completed trips for fare component mismatches
SELECT
    COUNT(*) AS COMPLETED_FARE_MISMATCHES
FROM TRIP_HEADERS t
JOIN TRIP_FARE_BREAKDOWN f
    ON t.TRIP_ID = f.TRIP_ID
WHERE t.TRIP_STATUS = 'COMPLETED'
  AND f.TOTAL_FARE_ZAR < (
      f.BASE_FARE_ZAR + f.TOLLS_ZAR + f.TIP_ZAR
  );


