-- V1. Check trip statuses and number of trips
SELECT
    TRIP_STATUS,
    COUNT(*) AS NUMBER_OF_TRIPS
FROM TRIP_HEADERS
GROUP BY TRIP_STATUS
ORDER BY NUMBER_OF_TRIPS DESC;


-- V2. Check for duplicate fare records per trip
SELECT
    TRIP_ID,
    COUNT(*) AS FARE_RECORDS
FROM TRIP_FARE_BREAKDOWN
GROUP BY TRIP_ID
HAVING COUNT(*) > 1
ORDER BY FARE_RECORDS DESC;


-- V3. Check trips without matching fare records
SELECT
    COUNT(*) AS TRIPS_WITHOUT_FARES
FROM TRIP_HEADERS t
LEFT JOIN TRIP_FARE_BREAKDOWN f
    ON t.TRIP_ID = f.TRIP_ID
WHERE f.TRIP_ID IS NULL;


-- V4. Calculate trip completion and cancellation rates
SELECT
    COUNT(*) AS TOTAL_TRIPS,
    SUM(CASE
        WHEN TRIP_STATUS = 'COMPLETED' THEN 1
        ELSE 0
    END) AS COMPLETED_TRIPS,
    SUM(CASE
        WHEN TRIP_STATUS = 'CANCELLED_BY_RIDER' THEN 1
        ELSE 0
    END) AS RIDER_CANCELLATIONS,
    SUM(CASE
        WHEN TRIP_STATUS = 'CANCELLED_BY_DRIVER' THEN 1
        ELSE 0
    END) AS DRIVER_CANCELLATIONS,
    ROUND(
        100 * SUM(CASE
            WHEN TRIP_STATUS = 'COMPLETED' THEN 1
            ELSE 0
        END) / COUNT(*), 2
    ) AS COMPLETION_RATE_PERCENT,
    ROUND(
        100 * SUM(CASE
            WHEN TRIP_STATUS IN (
                'CANCELLED_BY_RIDER',
                'CANCELLED_BY_DRIVER'
            ) THEN 1
            ELSE 0
        END) / COUNT(*), 2
    ) AS CANCELLATION_RATE_PERCENT
FROM TRIP_HEADERS;


