WHERE t.TRIP_STATUS = 'COMPLETED'
GROUP BY z.CITY, f.PAYMENT_METHOD, t.RIDE_CATEGORY
HAVING COUNT(*) >= 50
ORDER BY z.CITY, TIP_RATE_RANK_IN_CITY;
 
-- RQ5b. Rider-level tipper segments by home city
--       (top quartile of riders by personal tip rate)

WITH RIDER_TIP AS (
    SELECT
        r.RIDER_ID,
        r.HOME_CITY,
        COUNT(*) AS TRIPS,
        SUM(
            CASE WHEN NVL(f.TIP_ZAR, 0) > 0
                 THEN 1 ELSE 0 END
        ) AS TIPPED_TRIPS,
        SUM(NVL(f.TIP_ZAR, 0)) AS TOTAL_TIPS
    FROM SA_RIDERS r
    JOIN TRIP_HEADERS t
        ON r.RIDER_ID = t.RIDER_ID
    JOIN TRIP_FARE_BREAKDOWN f
        ON t.TRIP_ID = f.TRIP_ID
    WHERE t.TRIP_STATUS = 'COMPLETED'
    GROUP BY r.RIDER_ID, r.HOME_CITY
    HAVING COUNT(*) >= 5
),
QUARTILED AS (
    SELECT
        rt.*,
        TIPPED_TRIPS / TRIPS AS TIP_RATE,
        NTILE(4) OVER (
            ORDER BY TIPPED_TRIPS / TRIPS DESC
        ) AS TIP_QUARTILE
    FROM RIDER_TIP rt
)
SELECT
    HOME_CITY,
    COUNT(*) AS RIDERS,
    SUM(
        CASE WHEN TIP_QUARTILE = 1
             THEN 1 ELSE 0 END
    ) AS TOP_QUARTILE_TIPPERS,
    ROUND(
        100 * SUM(
            CASE WHEN TIP_QUARTILE = 1
                 THEN 1 ELSE 0 END
        ) / COUNT(*), 2
    ) AS PCT_TOP_QUARTILE,
    ROUND(100 * AVG(TIP_RATE), 2) AS AVG_TIP_RATE_PCT,
    ROUND(
        SUM(TOTAL_TIPS) / NULLIF(SUM(TRIPS), 0), 2
    ) AS AVG_TIP_PER_TRIP_ZAR
FROM QUARTILED
GROUP BY HOME_CITY
ORDER BY PCT_TOP_QUARTILE DESC;


